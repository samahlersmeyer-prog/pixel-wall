// Rasterizes U.S. states onto the wall's pixel grid and writes js/usmap-data.js.
import { readFileSync, writeFileSync } from 'node:fs';
import { feature } from 'topojson-client';
import { geoAlbersUsa, geoContains, geoCentroid } from 'd3-geo';

const MW = 88, MH = 56;
const S = {
  'Alabama': ['AL', 'Montgomery'], 'Alaska': ['AK', 'Juneau'], 'Arizona': ['AZ', 'Phoenix'], 'Arkansas': ['AR', 'Little Rock'],
  'California': ['CA', 'Sacramento'], 'Colorado': ['CO', 'Denver'], 'Connecticut': ['CT', 'Hartford'], 'Delaware': ['DE', 'Dover'],
  'District of Columbia': ['DC', 'Washington'], 'Florida': ['FL', 'Tallahassee'], 'Georgia': ['GA', 'Atlanta'], 'Hawaii': ['HI', 'Honolulu'],
  'Idaho': ['ID', 'Boise'], 'Illinois': ['IL', 'Springfield'], 'Indiana': ['IN', 'Indianapolis'], 'Iowa': ['IA', 'Des Moines'],
  'Kansas': ['KS', 'Topeka'], 'Kentucky': ['KY', 'Frankfort'], 'Louisiana': ['LA', 'Baton Rouge'], 'Maine': ['ME', 'Augusta'],
  'Maryland': ['MD', 'Annapolis'], 'Massachusetts': ['MA', 'Boston'], 'Michigan': ['MI', 'Lansing'], 'Minnesota': ['MN', 'Saint Paul'],
  'Mississippi': ['MS', 'Jackson'], 'Missouri': ['MO', 'Jefferson City'], 'Montana': ['MT', 'Helena'], 'Nebraska': ['NE', 'Lincoln'],
  'Nevada': ['NV', 'Carson City'], 'New Hampshire': ['NH', 'Concord'], 'New Jersey': ['NJ', 'Trenton'], 'New Mexico': ['NM', 'Santa Fe'],
  'New York': ['NY', 'Albany'], 'North Carolina': ['NC', 'Raleigh'], 'North Dakota': ['ND', 'Bismarck'], 'Ohio': ['OH', 'Columbus'],
  'Oklahoma': ['OK', 'Oklahoma City'], 'Oregon': ['OR', 'Salem'], 'Pennsylvania': ['PA', 'Harrisburg'], 'Rhode Island': ['RI', 'Providence'],
  'South Carolina': ['SC', 'Columbia'], 'South Dakota': ['SD', 'Pierre'], 'Tennessee': ['TN', 'Nashville'], 'Texas': ['TX', 'Austin'],
  'Utah': ['UT', 'Salt Lake City'], 'Vermont': ['VT', 'Montpelier'], 'Virginia': ['VA', 'Richmond'], 'Washington': ['WA', 'Olympia'],
  'West Virginia': ['WV', 'Charleston'], 'Wisconsin': ['WI', 'Madison'], 'Wyoming': ['WY', 'Cheyenne'],
};

const topo = JSON.parse(readFileSync('node_modules/us-atlas/states-10m.json', 'utf8'));
const all = feature(topo, topo.objects.states).features.filter(f => S[f.properties.name]);
all.sort((a, b) => a.properties.name.localeCompare(b.properties.name));
const proj = geoAlbersUsa().fitExtent([[0, 0], [MW - 1, MH - 1]], { type: 'FeatureCollection', features: all });

const grid = new Array(MW * MH).fill(-1);
for (let y = 0; y < MH; y++) for (let x = 0; x < MW; x++) {
  const ll = proj.invert([x + 0.5, y + 0.5]);
  if (!ll) continue;
  const i = all.findIndex(f => geoContains(f, ll));
  if (i >= 0) grid[y * MW + x] = i;
}
const states = all.map((f, i) => {
  const [abbr, capital] = S[f.properties.name];
  const c = geoCentroid(f);
  let p = proj(c) || [0, 0];
  let px = Math.max(0, Math.min(MW - 1, Math.round(p[0]))), py = Math.max(0, Math.min(MH - 1, Math.round(p[1])));
  // Make sure tiny states own at least their center pixel.
  if (!grid.includes(i)) grid[py * MW + px] = i;
  const cells = grid.reduce((n, v) => n + (v === i), 0);
  return { name: f.properties.name.toUpperCase(), abbr, capital: capital.toUpperCase(), lat: +c[1].toFixed(2), lon: +c[0].toFixed(2), x: px, y: py, cells };
});
const enc = grid.map(v => v < 0 ? '.' : String.fromCharCode(48 + v)).join('');
const out = `// Generated by tools/build-map.mjs from us-atlas (states-10m). Do not edit by hand.
export const MAP_W = ${MW};
export const MAP_H = ${MH};
// One character per pixel: '.' = no state, otherwise state index = charCode - 48.
export const MAP_GRID = ${JSON.stringify(enc)};
export const STATES = ${JSON.stringify(states)};
`;
writeFileSync(process.argv[2], out);
console.log('states', states.length, 'tiny:', states.filter(s => s.cells < 3).map(s => s.abbr + ':' + s.cells).join(' '));
for (let y = 0; y < MH; y++) console.log(enc.slice(y * MW, (y + 1) * MW).replace(/[^.]/g, '#'));
