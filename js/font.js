export const GLYPH_W = 5;
export const GLYPH_H = 7;

export function glyph(ch) {
  if (ch === ' ') return null;
  const g = G[ch] || G[ch.toUpperCase()];
  return g || G['?'];
}

// Pixels a character advances (glyph + 1 px gap); space is narrower.
export function advance(ch) {
  return ch === ' ' ? 4 : GLYPH_W + 1;
}
